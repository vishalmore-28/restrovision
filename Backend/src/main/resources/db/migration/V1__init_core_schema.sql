-- 9. AI Events, Alerts & Escalations
CREATE TABLE ai_events (
    ai_event_pk NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    event_uid VARCHAR2(40) NOT NULL,
    schema_version VARCHAR2(10) NOT NULL,
    edge_node_id VARCHAR2(60) NOT NULL,
    camera_id NUMBER,
    zone_id NUMBER,
    table_id NUMBER,
    event_type VARCHAR2(40) NOT NULL,
    confidence NUMBER(5,4),
    occurred_at TIMESTAMP NOT NULL,
    received_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    detected_at TIMESTAMP,
    model_versions CLOB,
    data_json CLOB,
    snapshot_ref VARCHAR2(500),
    processing_status VARCHAR2(20) DEFAULT 'RECEIVED' NOT NULL,
    CONSTRAINT uq_ai_event UNIQUE (restaurant_id, event_uid)
);

CREATE TABLE alerts (
    alert_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    ai_event_pk NUMBER,
    alert_type VARCHAR2(40) NOT NULL,
    priority VARCHAR2(10) NOT NULL,
    status VARCHAR2(15) DEFAULT 'OPEN' NOT NULL,
    dedupe_key VARCHAR2(200) NOT NULL,
    message VARCHAR2(255),
    table_id NUMBER,
    assigned_role VARCHAR2(20),
    assigned_employee_id NUMBER,
    escalation_level NUMBER(2) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP,
    acknowledged_by NUMBER,
    resolved_at TIMESTAMP,
    resolved_by NUMBER,
    version NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE alert_escalation_rules (
    rule_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    trigger_code VARCHAR2(60) NOT NULL,
    priority VARCHAR2(10) NOT NULL,
    first_recipient VARCHAR2(40) NOT NULL,
    escalate_after_seconds NUMBER(8),
    escalate_to VARCHAR2(40),
    dedupe_policy VARCHAR2(200),
    enabled CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT uq_escalation_rule UNIQUE (restaurant_id, trigger_code)
);

CREATE TABLE threshold_config (
    threshold_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    config_key VARCHAR2(80) NOT NULL,
    config_value VARCHAR2(200) NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_threshold UNIQUE (restaurant_id, config_key)
);

CREATE TABLE notification_history (
    notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    alert_id NUMBER,
    channel VARCHAR2(20) NOT NULL,
    recipient_ref VARCHAR2(120) NOT NULL,
    delivery_status VARCHAR2(20) NOT NULL,
    attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    delivered_at TIMESTAMP
);

