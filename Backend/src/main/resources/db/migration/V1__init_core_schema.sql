-- 1. Restaurants & Global Configuration
CREATE TABLE restaurants (
    restaurant_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(160) NOT NULL,
    timezone VARCHAR2(64) DEFAULT 'Asia/Kolkata' NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE restaurant_settings (
    restaurant_id NUMBER PRIMARY KEY REFERENCES restaurants(restaurant_id),
    settings_json CLOB DEFAULT '{}' NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Identity, RBAC & Security
CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    email VARCHAR2(254) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(160) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_user_email UNIQUE (restaurant_id, email),
    CONSTRAINT uq_user_tenant UNIQUE (restaurant_id, user_id)
);

CREATE TABLE roles (
    role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    role_code VARCHAR2(40) NOT NULL,
    role_name VARCHAR2(80) NOT NULL,
    CONSTRAINT uq_role_code UNIQUE (restaurant_id, role_code),
    CONSTRAINT uq_role_tenant UNIQUE (restaurant_id, role_id)
);

CREATE TABLE user_roles (
    restaurant_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    role_code VARCHAR2(40) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (restaurant_id, user_id, role_code),
    CONSTRAINT fk_ur_user FOREIGN KEY (restaurant_id, user_id) REFERENCES users (restaurant_id, user_id)
);

CREATE TABLE refresh_tokens (
    refresh_token_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_user FOREIGN KEY (restaurant_id, user_id) REFERENCES users (restaurant_id, user_id)
);

CREATE TABLE audit_logs (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    actor_user_id NUMBER,
    action VARCHAR2(100) NOT NULL,
    entity_type VARCHAR2(80) NOT NULL,
    entity_id VARCHAR2(80),
    before_json CLOB,
    after_json CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. Employees & Operations
CREATE TABLE employees (
    employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    user_id NUMBER,
    employee_code VARCHAR2(40) NOT NULL,
    display_name VARCHAR2(160) NOT NULL,
    job_role VARCHAR2(20) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT uq_employee_code UNIQUE (restaurant_id, employee_code),
    CONSTRAINT uq_employee_tenant UNIQUE (restaurant_id, employee_id)
);

CREATE TABLE shifts (
    shift_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    employee_id NUMBER NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    CONSTRAINT fk_shift_employee FOREIGN KEY (restaurant_id, employee_id) REFERENCES employees (restaurant_id, employee_id)
);

-- 4. Floor Layout, Tables & Sessions
CREATE TABLE restaurant_tables (
    table_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    table_code VARCHAR2(20) NOT NULL,
    capacity NUMBER(3) NOT NULL,
    status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    status_source VARCHAR2(10) DEFAULT 'SYSTEM' NOT NULL,
    status_changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    assigned_waiter_id NUMBER,
    current_session_id NUMBER,
    qr_token VARCHAR2(64),
    version NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT uq_table_code UNIQUE (restaurant_id, table_code),
    CONSTRAINT uq_table_tenant UNIQUE (restaurant_id, table_id)
);

CREATE TABLE table_sessions (
    session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    table_id NUMBER NOT NULL,
    status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    opened_by VARCHAR2(10) NOT NULL,
    seated_at TIMESTAMP NOT NULL,
    attended_at TIMESTAMP,
    ordered_at TIMESTAMP,
    departed_at TIMESTAMP,
    closed_at TIMESTAMP,
    party_size_est NUMBER(3),
    pre_attended_flag NUMBER(1) DEFAULT 0,
    CONSTRAINT uq_session_tenant UNIQUE (restaurant_id, session_id),
    CONSTRAINT fk_session_table FOREIGN KEY (restaurant_id, table_id) REFERENCES restaurant_tables (restaurant_id, table_id)
);

-- 5. Edge AI Infrastructure & Cameras
CREATE TABLE edge_nodes (
    edge_node_id VARCHAR2(60) PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    display_name VARCHAR2(100) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ONLINE' NOT NULL,
    last_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_edge_tenant UNIQUE (restaurant_id, edge_node_id)
);

CREATE TABLE cameras (
    camera_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    edge_node_id VARCHAR2(60) NOT NULL,
    name VARCHAR2(80) NOT NULL,
    location_desc VARCHAR2(200),
    credential_ref VARCHAR2(200),
    state VARCHAR2(15) DEFAULT 'CONNECTED' NOT NULL,
    last_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    target_fps NUMBER(4,1) DEFAULT 2.0 NOT NULL,
    CONSTRAINT uq_camera_tenant UNIQUE (restaurant_id, camera_id),
    CONSTRAINT fk_camera_edge FOREIGN KEY (restaurant_id, edge_node_id) REFERENCES edge_nodes (restaurant_id, edge_node_id)
);

CREATE TABLE camera_zones (
    zone_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    camera_id NUMBER NOT NULL,
    zone_type VARCHAR2(15) NOT NULL,
    table_id NUMBER,
    polygon_json CLOB NOT NULL,
    ref_width NUMBER(5) NOT NULL,
    ref_height NUMBER(5) NOT NULL,
    schedule_json CLOB,
    version NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT uq_zone_tenant UNIQUE (restaurant_id, zone_id),
    CONSTRAINT fk_zone_camera FOREIGN KEY (restaurant_id, camera_id) REFERENCES cameras (restaurant_id, camera_id)
);

-- 6. Kitchen & Menu Management
CREATE TABLE kitchen_stations (
    station_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    name VARCHAR2(100) NOT NULL,
    CONSTRAINT uq_station_name UNIQUE (restaurant_id, name),
    CONSTRAINT uq_station_tenant UNIQUE (restaurant_id, station_id)
);

CREATE TABLE menu_categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    name VARCHAR2(100) NOT NULL,
    display_order NUMBER(5) DEFAULT 0 NOT NULL,
    active CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT uq_category_name UNIQUE (restaurant_id, name),
    CONSTRAINT uq_category_tenant UNIQUE (restaurant_id, category_id)
);

CREATE TABLE menu_items (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    category_id NUMBER NOT NULL,
    station_id NUMBER,
    name VARCHAR2(160) NOT NULL,
    description VARCHAR2(1000),
    price NUMBER(12,2) NOT NULL,
    expected_prep_minutes NUMBER(5) DEFAULT 15 NOT NULL,
    available CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT uq_item_tenant UNIQUE (restaurant_id, item_id),
    CONSTRAINT fk_item_category FOREIGN KEY (restaurant_id, category_id) REFERENCES menu_categories (restaurant_id, category_id),
    CONSTRAINT fk_item_station FOREIGN KEY (restaurant_id, station_id) REFERENCES kitchen_stations (restaurant_id, station_id)
);

-- 7. Orders & Kitchen Display
CREATE TABLE orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    session_id NUMBER,
    table_id NUMBER,
    order_code VARCHAR2(40) NOT NULL,
    status VARCHAR2(20) DEFAULT 'CREATED' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT uq_order_code UNIQUE (restaurant_id, order_code),
    CONSTRAINT uq_order_tenant UNIQUE (restaurant_id, order_id)
);

CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    order_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    item_name VARCHAR2(160) NOT NULL,
    station_id NUMBER,
    station_name VARCHAR2(100),
    quantity NUMBER(5) NOT NULL,
    unit_price NUMBER(12,2) NOT NULL,
    expected_prep_minutes NUMBER(5) DEFAULT 15 NOT NULL,
    status VARCHAR2(20) DEFAULT 'CREATED' NOT NULL,
    preparation_started_at TIMESTAMP,
    ready_at TIMESTAMP,
    CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES orders (order_id)
);

CREATE TABLE order_status_history (
    history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id NUMBER NOT NULL REFERENCES restaurants(restaurant_id),
    order_id NUMBER NOT NULL,
    old_status VARCHAR2(20),
    new_status VARCHAR2(20) NOT NULL,
    changed_by NUMBER,
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_osh_order FOREIGN KEY (restaurant_id, order_id) REFERENCES orders (restaurant_id, order_id)
);

